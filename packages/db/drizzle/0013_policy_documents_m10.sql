## 제1조 (목적)

이 약관은 [입력: 상호](이하 "회사")가 운영하는 온라인 교육 사이트 AIONIT(이하 "사이트")에서 제공하는 강의 · 구독 · 그 밖의 서비스(이하 "서비스")의 이용 조건과 절차, 회사와 회원의 권리 · 의무를 정합니다.

## 제2조 (정의)

1. "회원"은 이 약관에 동의하고 가입해 사이트를 이용하는 사람입니다.
2. "강의"는 사이트에서 제공하는 교재 · 영상 · 실습 자료 · 퀴즈 등 학습 콘텐츠의 묶음입니다.
3. "수강권"은 정해진 기간 동안 강의를 볼 수 있는 권리입니다. 단건 구매 · 구독 · 운영자 발급으로 생깁니다.
4. "구독"은 정해진 금액을 매월 또는 매년 자동결제하고, 구독에 포함된 강의를 그 기간 동안 보는 서비스입니다.
5. "강사"는 회사와 별도 계약(강사 이용약관)을 맺고 강의를 올리는 회원입니다.

## 제3조 (약관의 게시와 변경)

1. 회사는 이 약관을 사이트 바닥글의 "이용약관"에 게시합니다. 지난 버전도 함께 볼 수 있습니다.
2. 회사는 관련 법령을 어기지 않는 범위에서 약관을 바꿀 수 있습니다. 바꿀 때는 시행일과 바뀌는 내용을 시행일 7일 전부터, 회원에게 불리한 변경은 30일 전부터 사이트에 알리고 이메일로도 알립니다. **[검토]** (약관규제법 · 전자상거래법 기준 기간)
3. 회원이 바뀐 약관에 동의하지 않으면 시행일 전까지 탈퇴할 수 있습니다. 시행일 뒤에도 계속 이용하면 동의한 것으로 봅니다. **[검토]** (묵시적 동의 문구의 효력)

## 제4조 (가입)

1. 만 14세 이상만 가입할 수 있습니다.
2. 이메일 또는 구글 · 카카오 계정으로 가입하며, 이용약관과 개인정보 수집 · 이용에 동의해야 합니다. 마케팅 정보 수신은 선택입니다.
3. 다른 사람의 정보로 가입하거나 거짓 정보를 넣은 경우 회사는 이용을 제한하거나 계약을 해지할 수 있습니다.

## 제5조 (계정 관리)

1. 회원은 자기 계정과 비밀번호를 스스로 관리하며, 다른 사람과 함께 쓰거나 빌려줄 수 없습니다.
2. 계정을 함께 쓰는 것으로 보이는 이용(동시에 여러 곳에서 접속 등)이 확인되면 회사는 확인을 요청하고, 응하지 않으면 이용을 제한할 수 있습니다. **[검토]** (제한 기준의 구체성)
3. 계정이 도용된 것을 알면 바로 비밀번호를 바꾸고 1:1 문의로 알려 주세요.

## 제6조 (서비스의 제공)

1. 회사는 강의 상세 화면에 수강 기간 · 가격 · 구성(챕터 · 영상 · 실습)을 표시합니다.
2. 교재는 강사가 고칠 수 있으며, 수강 중인 회원에게는 고친 버전이 보입니다. 큰 변경은 강의 소식으로 알립니다.
3. 서버 점검 등으로 서비스를 잠시 멈출 수 있으며, 미리 알 수 있는 경우 사이트에 먼저 알립니다.

## 제7조 (결제)

1. 결제는 토스페이먼츠를 통해 카드 등으로 합니다. 카드 정보는 회사가 저장하지 않습니다.
2. 구독 자동결제는 다른 동의와 따로 자동결제 동의를 받은 뒤에만 합니다. 결제일 · 금액은 구독 관리 화면에서 확인할 수 있습니다.
3. 구독 가격이 오르면 30일 전에 알리고 동의를 받습니다. 동의하지 않으면 그 회차부터 자동결제하지 않고 구독이 끝납니다.

## 제8조 (청약철회 · 환불)

청약철회와 환불은 "환불 정책"을 따릅니다. 환불 정책은 이 약관의 일부입니다. **[검토]** (전자상거래법 제17조, 디지털콘텐츠 청약철회 제한 고지 방식)

## 제9조 (회원의 의무)

회원은 다음을 해서는 안 됩니다.

- 강의 내용(교재 · 영상 · 실습 자료)을 허락 없이 복제 · 배포 · 판매 · 공유하는 일
- 영상 녹화 · 워터마크 제거 등 콘텐츠 보호 장치를 피하는 일
- 다른 회원을 괴롭히거나 Q&A 에 광고 · 불법 정보를 올리는 일
- 사이트의 보안을 해치거나 자동화 도구로 비정상적으로 접속하는 일

## 제10조 (게시물)

1. Q&A 등에 회원이 쓴 글의 저작권은 회원에게 있습니다. 회사는 서비스 안에서 보여 주는 데 필요한 범위에서만 씁니다.
2. 신고되었거나 제9조에 어긋나는 글은 사유를 남기고 숨길 수 있습니다.
3. 탈퇴해도 Q&A 에 쓴 글은 다른 수강생의 학습을 위해 남고, 글쓴이는 "탈퇴한 회원"으로 보입니다. 지우고 싶은 글은 탈퇴 전에 지워 주세요. **[검토]** (탈퇴 뒤 게시물 존치 동의)

## 제11조 (이용 제한 · 계약 해지)

1. 회원은 언제든 마이페이지에서 탈퇴할 수 있습니다. 탈퇴하면 수강권 · 구독이 끝나며, 환불이 필요하면 탈퇴 전에 요청해야 합니다.
2. 회원이 제9조를 어기면 회사는 경고 · 이용 정지 · 계약 해지를 할 수 있고, 그 사유를 알립니다. **[검토]** (해지 시 남은 수강권 환불 여부)

## 제12조 (책임의 한계)

1. 회사는 천재지변 · 통신 장애처럼 회사의 잘못이 없는 사유로 서비스를 제공하지 못한 경우 책임을 지지 않습니다.
2. 회사의 잘못으로 수강하지 못한 기간이 있으면 그만큼 수강 기간을 늘려 드립니다. **[검토]** (콘텐츠이용자보호지침 보상 기준)

## 제13조 (분쟁 해결)

1. 불만 · 분쟁은 1:1 문의로 접수하며, 회사는 영업일 기준 3일 안에 답합니다. 1:1 문의 기록은 분쟁 해결을 위해 3년 보관합니다.
